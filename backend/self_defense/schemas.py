"""
backend/self_defense/schemas.py

Pydantic schemas and models for Stage 2 Self-Defense subsystem.
Includes Audit Ledger records, external anchors, verification results,
and out-of-band security alerts.
"""

from enum import Enum
from typing import Dict, Any, Optional, List
import uuid
import time
from datetime import datetime, timezone
from pydantic import BaseModel, Field, ConfigDict


def get_utc_now_timestamp() -> float:
    return time.time()


def get_utc_now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


class TamperType(str, Enum):
    NONE = "NONE"
    MODIFIED = "MODIFIED"
    DELETED = "DELETED"
    INSERTED = "INSERTED"
    REORDERED = "REORDERED"
    ANCHOR_MISMATCH = "ANCHOR_MISMATCH"
    SIGNATURE_INVALID = "SIGNATURE_INVALID"
    SEQUENCE_CORRUPTED = "SEQUENCE_CORRUPTED"


class AuditRecord(BaseModel):
    """
    Cryptographically sealed append-only audit record.
    Chained via SHA-256 prev_hash and signed with an isolated HMAC key.
    """
    model_config = ConfigDict(extra="allow", populate_by_name=True)

    sequence_number: int = Field(..., description="Monotonically increasing sequence number starting at 1")
    entry_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    timestamp: float = Field(default_factory=get_utc_now_timestamp)
    timestamp_iso: str = Field(default_factory=get_utc_now_iso)
    tenant_id: str = Field(default="global")
    actor: Dict[str, Any] = Field(default_factory=dict, description="User or agent performing the action")
    action: str = Field(..., description="Action name, e.g. CONFIG_UPDATE, SENSOR_REVOKED")
    resource_type: str = Field(..., description="Resource category: sensor, rule, model, user, config")
    resource_id: str = Field(..., description="Identifier of the target resource")
    details: Dict[str, Any] = Field(default_factory=dict, description="Metadata or parameters of the action")
    status: str = Field(default="SUCCESS", description="SUCCESS, FAILED, DENIED")
    
    # Cryptographic integrity fields
    prev_hash: str = Field(..., description="SHA-256 hash of the immediately preceding record")
    entry_hash: str = Field(..., description="SHA-256 hash of this record's canonical payload + prev_hash")
    signature: str = Field(..., description="HMAC-SHA256 signature generated with isolated signing key")


class AuditAnchor(BaseModel):
    """
    External anchor snapshot capturing a sealed checkpoint of the audit chain.
    Persisted to independent, out-of-band durable storage.
    """
    model_config = ConfigDict(extra="allow", populate_by_name=True)

    anchor_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    sequence_number: int = Field(..., description="The sequence number anchored")
    entry_hash: str = Field(..., description="The entry hash anchored at this sequence")
    timestamp: float = Field(default_factory=get_utc_now_timestamp)
    timestamp_iso: str = Field(default_factory=get_utc_now_iso)
    signature: str = Field(..., description="HMAC-SHA256 signature over sequence_number + entry_hash")


class AuditVerificationResult(BaseModel):
    """
    Detailed verdict of the audit chain mathematical verification.
    """
    model_config = ConfigDict(extra="allow")

    is_valid: bool = Field(..., description="True if and only if entire chain and all anchors are intact")
    total_records: int = Field(default=0)
    verified_anchors: int = Field(default=0)
    tamper_detected: bool = Field(default=False)
    tamper_type: TamperType = Field(default=TamperType.NONE)
    tampered_sequence: Optional[int] = None
    tampered_entry_id: Optional[str] = None
    error_message: Optional[str] = None
    checked_at: float = Field(default_factory=get_utc_now_timestamp)
    checked_at_iso: str = Field(default_factory=get_utc_now_iso)


